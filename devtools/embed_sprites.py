"""Embed assets/sprites/*.png (and the face parts in assets/sprites/parts) into src/claude_pet/sprite_data.py
so a one-file exe carries its art.

The factory's PyInstaller step bundles code, not loose data files, so the sprites travel as
base64 WebP inside a module. Re-run after changing sprites; a test fails if the module is stale.

usage: python devtools/embed_sprites.py [sprites_dir] [output_module]
       python devtools/embed_sprites.py --girl <id>   (assets/characters/<id> -> sprite_data_<id>.py)

Claude's set must be whole: her eight moods and all of her face parts. A new girl (--girl) needs her eight moods
and the idle and talk parts; each other expression's parts come all or none (made with devtools/make_face_parts.py
--girl <id>; an expression without them simply keeps still). An incomplete set is refused and the old module kept.
"""
from __future__ import annotations

import base64
import hashlib
import io
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from claude_pet.sprites import IDLE_PARTS, MOOD_PARTS, PARTS, TALK_EYES  # noqa: E402  the same lists the app loads
MOODS = ("idle", "talk", "happy", "think", "panic", "angry", "sad", "sleep")
HEADER = '"""Sprites as base64 WebP. Generated by devtools/embed_sprites.py - do not edit by hand."""\n'


def encode(path: Path) -> bytes:
    buffer = io.BytesIO()
    Image.open(path).convert("RGBA").save(buffer, format="WEBP", quality=92, alpha_quality=100, method=4)
    return buffer.getvalue()


def source_hashes(folder: Path, names: tuple[str, ...]) -> dict[str, str]:
    return {name: hashlib.sha256((folder / f"{name}.png").read_bytes()).hexdigest() for name in names}


def _table(prefix: str, folder: Path, names: tuple[str, ...]) -> list[str]:
    lines = [f"# SHA-256 of the PNGs this was built from; tests compare them with {folder.name}.", f"{prefix}SOURCES = {{"]
    lines.extend(f'    "{name}": "{digest}",' for name, digest in source_hashes(folder, names).items())
    encoded = {name: encode(folder / f"{name}.png") for name in names}
    # Lossy WebP decoders tolerate damaged bitstreams without an error, so integrity is checked by hash.
    lines += ["}", "", "# SHA-256 of each embedded WebP; checked before decoding.", f"{prefix}CHECKSUMS = {{"]
    lines.extend(f'    "{name}": "{hashlib.sha256(webp).hexdigest()}",' for name, webp in encoded.items())
    lines += ["}", "", f"{prefix}{'SPRITES' if not prefix else 'IMAGES'} = {{"]
    for name in names:
        data = base64.b64encode(encoded[name]).decode("ascii")
        chunks = [data[i:i + 100] for i in range(0, len(data), 100)]
        lines.append(f'    "{name}": (')
        lines.extend(f'        "{chunk}"' for chunk in chunks)
        lines.append("    ),")
    lines.append("}")
    return lines


def render(sprites_dir: Path) -> str:
    lines = [HEADER, *_table("", sprites_dir, MOODS),
             "", "# Face overlay parts (blink and talk), cropped like the sprites.",
             *_table("PART_", sprites_dir / "parts", present_parts(sprites_dir))]
    return "\n".join(lines) + "\n"


def present_parts(sprites_dir: Path) -> tuple[str, ...]:
    return tuple(n for n in PARTS if (sprites_dir / "parts" / f"{n}.png").is_file())


def missing(sprites_dir: Path, whole: bool = True) -> list[Path]:
    needed = [sprites_dir / f"{mood}.png" for mood in MOODS]
    for mood, names in MOOD_PARTS.items():  # an expression's parts: all or none (all, for Claude)
        started = any((sprites_dir / "parts" / f"{mood}_{n}.png").is_file() for n in names)
        if whole or started:
            needed += [sprites_dir / "parts" / f"{mood}_{n}.png" for n in names]
    needed += [sprites_dir / "parts" / f"{n}.png" for n in IDLE_PARTS + TALK_EYES]
    return [path for path in needed if not path.is_file()]


def main(sprites_dir: Path, output: Path, whole: bool = True) -> int:
    absent = missing(sprites_dir, whole)
    if absent:  # an incomplete set would silently switch animations off in the exe: keep the old module
        for path in absent:
            print(f"[missing] {path}")
        print(f"{output} left unchanged")
        return 1
    text = render(sprites_dir)
    output.write_text(text, encoding="utf-8", newline="\n")
    print(f"[ok] {output} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    args = sys.argv[1:]
    if args[:1] == ["--girl"] and len(args) == 2:
        sprites = ROOT / "assets" / "characters" / args[1]
        out = ROOT / "src" / "claude_pet" / f"sprite_data_{args[1]}.py"
        raise SystemExit(main(sprites, out, whole=False))
    sprites = Path(args[0]) if args else ROOT / "assets" / "sprites"
    out = Path(args[1]) if len(args) > 1 else ROOT / "src" / "claude_pet" / "sprite_data.py"
    raise SystemExit(main(sprites, out))

"""Embed assets/sprites/*.png (and the face parts in assets/sprites/parts) into src/claude_pet/sprite_data.py
so a one-file exe carries its art.

The factory's PyInstaller step bundles code, not loose data files, so the sprites travel as
base64 WebP inside a module. Re-run after changing sprites; a test fails if the module is stale.

usage: python devtools/embed_sprites.py [sprites_dir] [output_module]
"""
from __future__ import annotations

import base64
import hashlib
import io
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MOODS = ("idle", "talk", "happy", "think", "panic", "angry", "sad", "sleep")
PARTS = ("eyes_half", "eyes_closed", "mouth_half", "mouth_open", "mouth_o", "mouth_closed")
HEADER = '"""Sprites as base64 WebP. Generated by devtools/embed_sprites.py - do not edit by hand."""\n'


def encode(path: Path) -> bytes:
    buffer = io.BytesIO()
    Image.open(path).convert("RGBA").save(buffer, format="WEBP", quality=92, alpha_quality=100, method=4)
    return buffer.getvalue()


def source_hashes(folder: Path, names: tuple[str, ...]) -> dict[str, str]:
    return {name: hashlib.sha256((folder / f"{name}.png").read_bytes()).hexdigest() for name in names}


def _table(prefix: str, folder: Path, names: tuple[str, ...]) -> list[str]:
    lines = [f"# SHA-256 of the PNGs this was built from; tests compare them with {folder.name}.", f"{prefix}SOURCES = {{"]
    lines.extend(f'    "{name}": "{digest}",' for name, digest in source_hashes(folder, names).items())
    encoded = {name: encode(folder / f"{name}.png") for name in names}
    # Lossy WebP decoders tolerate damaged bitstreams without an error, so integrity is checked by hash.
    lines += ["}", "", "# SHA-256 of each embedded WebP; checked before decoding.", f"{prefix}CHECKSUMS = {{"]
    lines.extend(f'    "{name}": "{hashlib.sha256(webp).hexdigest()}",' for name, webp in encoded.items())
    lines += ["}", "", f"{prefix}{'SPRITES' if not prefix else 'IMAGES'} = {{"]
    for name in names:
        data = base64.b64encode(encoded[name]).decode("ascii")
        chunks = [data[i:i + 100] for i in range(0, len(data), 100)]
        lines.append(f'    "{name}": (')
        lines.extend(f'        "{chunk}"' for chunk in chunks)
        lines.append("    ),")
    lines.append("}")
    return lines


def render(sprites_dir: Path) -> str:
    lines = [HEADER, *_table("", sprites_dir, MOODS), "", "# Face overlay parts (blink and talk), cropped like the sprites.",
             *_table("PART_", sprites_dir / "parts", PARTS)]
    return "\n".join(lines) + "\n"


def main(sprites_dir: Path, output: Path) -> int:
    text = render(sprites_dir)
    output.write_text(text, encoding="utf-8", newline="\n")
    print(f"[ok] {output} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    args = sys.argv[1:]
    sprites = Path(args[0]) if args else ROOT / "assets" / "sprites"
    out = Path(args[1]) if len(args) > 1 else ROOT / "src" / "claude_pet" / "sprite_data.py"
    raise SystemExit(main(sprites, out))
